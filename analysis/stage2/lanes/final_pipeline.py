"""Lane final: the final model, its calibration and its export. Steps: compute (experiments, derived data, export),
figures, tables, numbers (+ final_SUMMARY.md).

    cd analysis
    .venv/Scripts/python.exe -m stage2.pipeline compute --lanes final            # missing experiments + derive + export
    .venv/Scripts/python.exe -m stage2.pipeline compute --lanes final --only final_derive --force   # derive only
    .venv/Scripts/python.exe -m stage2.pipeline figures --lanes final            # redraw from saved files
    .venv/Scripts/python.exe -m stage2.pipeline tables --lanes final
    .venv/Scripts/python.exe -m stage2.pipeline numbers --lanes final            # final_numbers.json + summary

Worker processes may share the experiments: ``python -m stage2.lanes.final_nested --jobs @jobs.txt`` fills the
inner-prediction cache of the nested selection and ``python -m stage2.lanes.final_experiments --names ...`` runs
named experiments; the compute step then finds them current and only derives.
"""
from stage2.pipeline import Lane, limit_threads

limit_threads(3)

import json  # noqa: E402
import time  # noqa: E402
from typing import Any  # noqa: E402

L = Lane('final')
ORDER = 900
DEPENDS = ('m1', 'm2', 'm3', 'm4', 'p1')

#: THE analyst decision of this lane: the candidate (``final_candidates`` key) that produces P(right) in production.
#: Evidence: tables/final/final_decision.csv (regenerated by the pipeline) and the rule in final_finalmodel.recommend.
FINAL_MODEL = 'm3_deep'

#: derived steps of compute (selectable with --only)
DERIVED = ('final_reproduction', 'final_derive', 'final_export')


def compute(force: bool = False, only: list[str] | None = None) -> None:
    from stage2.pipeline import selected
    from stage2.lanes import final_candidates as FC
    from stage2.lanes import final_experiments as FE
    cands = FC.candidates()
    plan = FE.plan(cands, FINAL_MODEL)
    todo = [s for s in plan if L.should_run(s.name, force, only)]
    need_rep = selected('final_reproduction', only) and (force or not (L.tab_dir / 'final_reproduction.json').exists())
    D = None
    if todo or need_rep:
        D = FE.load_data()
    if need_rep:
        for k, c in cands.items():
            if c.source:
                t0 = time.time()
                out = FE.reproduce(c, cands, D)
                FE.save_reproduction(out)
                print(f'final: reproduced {k} max|dP| {out["max_abs_dp_primary"]:.1e} ({time.time() - t0:.0f} s)',
                      flush=True)
    if todo:
        blocks = FE.label_noise_blocks(D.d)
        for s in todo:
            t0 = time.time()
            r = FE.run_spec(s, cands, D, blocks)
            print(f'final: {s.name} accuracy {r.metrics["accuracy"]:.4f} log loss {r.metrics["log_loss"]:.4f} '
                  f'{r.leak_check} ({time.time() - t0:.0f} s)', flush=True)
    elif not need_rep:
        print('final: experiments current; skipped (--force recomputes)', flush=True)
    if selected('final_derive', only) or todo:
        derive(cands)
    if selected('final_export', only) or todo:
        from stage2.lanes import final_export
        final_export.export(FINAL_MODEL)


def derive(cands: Any = None) -> None:
    """Every derived analysis from the saved results (tables/final/final_*.json)."""
    from stage2.data import load_cache
    from stage2.lanes import final_candidates as FC
    from stage2.lanes import final_derive as FD
    from stage2.lanes import final_experiments as FE
    from stage2.lanes import final_finalmodel as FF
    from stage2.lanes.final_io import clean
    cands = cands or FC.candidates()

    def put(name: str, obj: Any) -> None:            # JSON has no NaN: a missing number is written as null
        L.write_json(name, clean(obj))
    d, nat = load_cache(), load_cache(('natural_use',))
    tt = FD.trial_table(d)
    rep_p = L.tab_dir / 'final_reproduction.json'
    repro = {r['key']: r for r in (json.loads(rep_p.read_text(encoding='utf-8'))['rows'] if rep_p.exists() else [])}
    t0 = time.time()
    master = FD.master(cands, repro)
    put('final_master', {'rows': master, 'candidates': [FC.describe(c) for c in cands.values()]})
    put('final_overview', {'rows': FD.registry_overview()})
    nested = FD.nested(cands, master)
    put('final_nested', nested)
    paired = FD.paired_families(cands, master)
    put('final_paired', paired)
    put('final_input_class', {'rows': FD.input_vs_class(cands)})
    flipcheck = {k: FD.flip_inputs_unchanged(c, d) for k, c in cands.items() if FE.flip_invariant(c)}
    rob = FD.robustness(cands, d, tt)
    put('final_robustness', {'rows': rob, 'flip_invariant_max_abs_input_change': flipcheck,
                                      'label_noise_blocks': [list(b) for b in FE.label_noise_blocks(d)]})
    nat_rows = FD.natural_test(cands)
    comp = {k: FD.component_transfer(k, cands, d, nat) for k, c in cands.items()
            if c.input == 'm3body' and not c.components}
    put('final_natural', {'rows': nat_rows, 'components': {k: v for k, v in comp.items() if v}})
    dec = FF.decision_table(cands, master, paired, rob, nat_rows, nested)
    dec['final_model'] = FINAL_MODEL
    dec['agrees_with_rule'] = bool(dec['recommended'] == FINAL_MODEL)
    put('final_decision', dec)
    print(f'final: derived master, nested, paired, robustness, natural use, decision ({time.time() - t0:.0f} s); '
          f'rule recommends {dec["recommended"]}, FINAL_MODEL = {FINAL_MODEL}', flush=True)
    c = cands[FINAL_MODEL]
    base_name = FE.base_result_name(c)
    cal = FF.calibration(FINAL_MODEL, tt)
    put('final_calibration', cal)
    chosen = (cal or {}).get('chosen', 'none')
    put('final_aggregation', FF.aggregation(FINAL_MODEL, cands, d, chosen))
    shipped = f'final_cal_{FINAL_MODEL}_{chosen}' if FD.exists(f'final_cal_{FINAL_MODEL}_{chosen}') else base_name
    put('final_shipped', FF.shipped_summary(shipped, FINAL_MODEL, chosen))
    put('final_breakdown', {'result': shipped, **FF.breakdowns(shipped, tt)})
    put('final_variants', {'rows': FF.variants(FINAL_MODEL, base_name)})
    put('final_remedies', FF.remedies_final(FINAL_MODEL, cands))
    put('final_learning', FF.learning_curve(list(dict.fromkeys([FINAL_MODEL, 'ref'])), cands))
    put('final_prior', {'rows': FF.prior_shift(shipped), 'result': shipped})
    from stage2.lanes import final_summary
    put('final_finalist_check', FE.check_finalist(final_summary.finalist_entry()))
    print(f'final: derived the final model analyses ({time.time() - t0:.0f} s)', flush=True)


def figures(force: bool = False, only: list[str] | None = None) -> None:
    from stage2.lanes import final_figures
    final_figures.draw(only)


def tables(force: bool = False, only: list[str] | None = None) -> None:
    from stage2.lanes import final_report
    final_report.tables(only)


def numbers(force: bool = False, only: list[str] | None = None) -> None:
    from stage2.lanes import final_summary
    final_summary.build()
    final_summary.finalists()


STEPS = {'compute': compute, 'figures': figures, 'tables': tables, 'numbers': numbers}
