def _figure_counts(n: Num, master: dict[str, Any]) -> None:
    """Counts that the figure captions state, registered so that every caption number is an entry."""
    import pandas as pd
    src_m = _src('final_master')
    n('n_exploratory_candidates', int(sum(r['n_configs_tried'] > 1 for r in master.values())), 'd', src_m,
      'candidates chosen on the outer folds in their lane (n_configs_tried > 1)')
    # sizes that the candidate labels and descriptions state (computed from the code that defines them)
    from stage2.lanes import final_features as FFt
    from stage2.lanes import final_models as FM
    n('lr_body_tc_n_features', len(FM.TC_CHANNELS) * FM.TC_BINS, 'd', 'stage2/lanes/final_models.py',
      'features of the body-frame time-course logistic (channels x time bins)')
    n('m2_n_features', int(len(FFt.registry('m2'))), 'd', 'stage2/lanes/m2_features.py',
      'features of lane m2\'s default feature families (17 channels)')
    n('person_threshold', 0.8, '.0%', 'final_summary_body', 'person accuracy threshold of the breakdown count')
    if _has('final_overview'):
        ov = pd.DataFrame(_read('final_overview')['rows']).dropna(subset=['accuracy', 'log_loss'])
        ov = ov[ov['log_loss'] < 1.2]
        n('overview_n', len(ov), 'd', _src('final_overview'), 'registry experiments with a log loss below 1.2')
        n('overview_exploratory', int(ov['exploratory'].sum()), 'd', _src('final_overview'),
          'of them compared on the outer folds before being kept')
    if _has('final_robustness'):
        rob = _read('final_robustness')['rows']
        srb = _src('final_robustness')
        n('n_flip_below_chance', int(sum((r.get('flip') or {}).get('acc_flipped', 1.0) < 0.5 for r in rob)), 'd',
          srb, 'candidates below chance on the screen-away twins without the check')
        grip = [r['grip'] for r in rob if r.get('grip')]
        n('fig_grip_tested', len(grip), 'd', srb, 'candidates with a grip-transfer run')
        n('fig_grip_fail', int(sum(g['holm_acc'] < 0.05 and g['d_acc'] < 0 for g in grip)), 'd', srb,
          'candidates whose accuracy drops on the rotated grips (Holm p below 0.05)')
        flips = [(r['key'], r['flip']) for r in rob if r.get('flip') and not r['flip'].get('invariant_inputs')]
        n('fig_flip_tested', len(flips), 'd', srb, 'candidates whose inputs change under the screen flip')
        n('fig_flip_fail', int(sum(f['holm_acc'] < 0.05 and f['d_acc'] < 0 for _, f in flips)), 'd', srb,
          'candidates whose accuracy drops on the screen-away twins (Holm p below 0.05)')
        n('fig_flip_fixed', int(sum(f['acc_flipped_remedy'] >= master[k]['accuracy'] - 0.05 for k, f in flips)), 'd',
          srb, 'candidates that the rest-pose check brings back within 5 points of the recorded accuracy')
    if _has('final_breakdown'):
        pp = pd.DataFrame(_read('final_breakdown')['persons'])
        n('n_left_handed', int((pp['handedness'].astype(str).str.lower() == 'left').sum()), 'd',
          _src('final_breakdown'), 'left-handed persons')
