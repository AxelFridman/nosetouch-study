"""Lane final: the numbers file (results/final_numbers.json), the summary (reports/stage2/final_SUMMARY.md) and the
finalists file, from saved files only. Every number of the summary is written through :class:`Num`, which records it
in the numbers file with its source, so the summary cites nothing that is not an entry; every decision sentence is
generated from the saved results."""
from __future__ import annotations

import math
from typing import Any

import numpy as np

from stage2 import report_export as RX
from stage2.pipeline import Lane

L = Lane('final')
E = RX.numbers_entry


class Num:
    """Collects numbers-file entries and returns their formatted text."""

    def __init__(self) -> None:
        self.entries: dict[str, dict[str, Any]] = {}

    def __call__(self, key: str, value: Any, fmt: str, source: str, desc: str) -> str:
        if hasattr(value, 'item'):
            value = value.item()
        if isinstance(value, float) and not math.isfinite(value):
            value = None
        self.entries[key] = E(value, fmt, source, desc)
        return RX.format_value(value, fmt)

    def pct(self, key: str, value: float, source: str, desc: str) -> str:
        return self(key, value, '.1%', source, desc)

    def ci(self, key: str, ci: Any, source: str, desc: str, fmt: str = '.1%') -> str:
        a = self(f'{key}_lo', ci[0], fmt, source, f'{desc}: 95 % CI low')
        b = self(f'{key}_hi', ci[1], fmt, source, f'{desc}: 95 % CI high')
        return f'[{a}, {b}]'

    def pts(self, key: str, value: float, source: str, desc: str) -> str:
        return self(key, 100 * value, '+.1f', source, f'{desc} (points)')

    def pts_ci(self, key: str, ci: Any, source: str, desc: str) -> str:
        a = self(f'{key}_lo', 100 * ci[0], '+.1f', source, f'{desc}: 95 % CI low (points)')
        b = self(f'{key}_hi', 100 * ci[1], '+.1f', source, f'{desc}: 95 % CI high (points)')
        return f'[{a}, {b}]'

    def p(self, key: str, value: float | None, source: str, desc: str) -> str:
        if value is None or not np.isfinite(value):
            return self(key, None, '.3f', source, desc)
        if value < 0.001:
            self.entries[key] = E('< 0.001', '', source, desc)
            return '< 0.001'
        return self(key, value, '.3f', source, desc)


def _src(name: str) -> str:
    return f'tables/final/{name}.json'


def _read(name: str) -> dict[str, Any]:
    from stage2.lanes.final_io import denull
    return denull(L.read_json(name))


def _has(name: str) -> bool:
    return (L.tab_dir / f'{name}.json').exists()


def build() -> None:
    from stage2.lanes import final_experiments as FE
    from stage2.lanes import final_figures as FF
    from stage2.lanes import final_report as FR
    n = Num()
    S: list[str] = []
    w = S.append
    master = {r['key']: r for r in _read('final_master')['rows']}
    lab = {k: r['label'] for k, r in master.items()}
    dec = _read('final_decision')
    fin = dec['final_model']
    fm = master[fin]
    src_m, src_d = _src('final_master'), _src('final_decision')
    for k, r in master.items():
        n.pct(f'{k}_accuracy', r['accuracy'], src_m, f'{r["label"]}: LOSO accuracy')
        n.ci(f'{k}_accuracy', r['accuracy_ci'], src_m, f'{r["label"]}: accuracy')
        n(f'{k}_auc', r['auc'], '.3f', src_m, f'{r["label"]}: AUC')
        n(f'{k}_log_loss', r['log_loss'], '.3f', src_m, f'{r["label"]}: log loss')
        n.ci(f'{k}_log_loss', r['log_loss_ci'], src_m, f'{r["label"]}: log loss', '.3f')
        n(f'{k}_ece', r['cal_ece'], '.3f', src_m, f'{r["label"]}: ECE (10 equal-mass bins)')
        n(f'{k}_ece_null_q', r['cal_ece_null_q95'], '.3f', src_m, f'{r["label"]}: 95th percentile of its ECE null')
        n(f'{k}_slope', r['cal_slope'], '.2f', src_m, f'{r["label"]}: calibration slope')
        n.pct(f'{k}_kthree', r['k3'], src_m, f'{r["label"]}: accuracy with k = 3 attempts (mean P)')
        n.pct(f'{k}_nat_recall', r['nat_recall'], src_m, f'{r["label"]}: natural-use right-hand recall')
        n(f'{k}_configs', int(r['n_configs_tried']), 'd', src_m, f'{r["label"]}: outer-fold configurations in its lane')
    w('# Lane final: the final model, its calibration and its export\n')
    w('*Generated by `python -m stage2.pipeline numbers --lanes final` from the saved results; every number below is an '
      'entry of `results/final_numbers.json` (LaTeX macros `\\Final...` in `results/numbers.tex`). Do not edit by hand.*\n')
    w('## Goal\n')
    w('Choose the model that produces the percentage P(right) in production, with an honest, selection-aware estimate of '
      'its performance, justified by accuracy, calibration, robustness to unknown test conditions, transfer to natural '
      'use, simplicity and portability; fit it on all persons and export it as plain JSON with a numpy reference '
      'implementation for the Stage 3 JavaScript port.\n')
    n_c = n('n_candidates', len(master), 'd', src_m, 'candidates of the cross-lane selection')
    w('## Evaluation contract\n')
    w(f'- Leave-one-person-out through `stage2.cv.run_experiment` (one outer fold per person, D2 cap, leak check on every '
      f'fold unless a result says otherwise); natural-use trials scored apart: every reported hand so far is the right '
      f'hand, so natural-use accuracy is right-hand recall only (a constant "right" would score all of them).\n'
      f'- 95 % CIs: person-cluster bootstrap. Paired comparisons: mean per-person difference on the same trials, paired '
      f'person bootstrap and the exact sign-flip test over persons (`cv.paired_compare`); Holm within each named '
      f'family.\n'
      f'- {n_c} candidates: every trial-level finalist of lanes m1, m2, m3 and p1 (read from their finalists files), the '
      f'reference floor, three engineered models given the body-frame channels (task 2b) and one pre-specified '
      f'cross-lane ensemble (mean logit of one finalist per lane). Lane m4 (cue-free recordings) and x1 (PD01, '
      f'descriptive) are not trial-level candidates.\n'
      f'- Calibration standard: ECE with its perfect-calibration null band, calibration slope and intercept with person-'
      f'bootstrap CIs, paired log-loss and Brier differences; "miscalibrated" only when a slope / intercept CI excludes '
      f'1 / 0 or the ECE lies outside its null band.\n')
    # ── headline
    cal = _read('final_calibration') if _has('final_calibration') else {}
    chosen = cal.get('chosen', 'none')
    ns = _read('final_nested') if _has('final_nested') else {}
    src_n, src_c = _src('final_nested'), _src('final_calibration')
    w('## Headline\n')
    sh = _read('final_shipped') if _has('final_shipped') else None
    src_s = _src('final_shipped')
    w(f'**Final model: {fm["label"]}** (`FINAL_MODEL = \'{fin}\'` in `stage2/lanes/final_pipeline.py`; {fm["family"]}; '
      f'{fm["representation"]}; {fm["treatment"]}' + (f'; shipped with the calibration remedy **{sh["remedy"]}**, '
                                                      f'result `{sh["result"]}`' if sh else '') + ').\n')
    if sh:
        k3 = sh['k_curve'].get('3') or sh['k_curve'].get(3)
        nat_s = sh['natural']
        w(f'- LOSO accuracy {n.pct("final_accuracy", sh["accuracy"], src_s, "final model as shipped: accuracy")} '
          f'{n.ci("final_accuracy", sh["accuracy_ci"], src_s, "final model as shipped: accuracy")}, AUC '
          f'{n("final_auc", sh["roc_auc"], ".3f", src_s, "final model as shipped: AUC")} '
          f'{n.ci("final_auc", sh["roc_auc_ci"], src_s, "final model as shipped: AUC", ".3f")}, log loss '
          f'{n("final_log_loss", sh["log_loss"], ".3f", src_s, "final model as shipped: log loss")} '
          f'{n.ci("final_log_loss", sh["log_loss_ci"], src_s, "final model as shipped: log loss", ".3f")}, Brier '
          f'{n("final_brier", sh["brier"], ".3f", src_s, "final model as shipped: Brier score")} '
          f'({n("final_n_trials", sh["n_trials"], "d", src_s, "primary trials")} trials of '
          f'{n("final_n_persons", sh["n_persons"], "d", src_s, "persons")} persons, leak check {sh["leak_check"]}); '
          f'{n("final_configs", int(fm["n_configs_tried"]), "d", src_m, "final model: outer-fold configurations in its lane")} '
          f'configuration(s) were compared on the outer folds in its own lane before it became a candidate, and this lane '
          f'chose it among the {n_c} candidates by the decision rule: these numbers are exploratory (optimistic), the '
          f'nested estimate below is the selection-aware one.\n')
        w(f'- Natural use, right-hand recall on the free-choice trials (not a balanced accuracy: every reported hand is '
          f'the right one): {n.pct("final_nat_recall", nat_s.get("recall", float("nan")), src_s, "final model as shipped: natural-use right-hand recall")} '
          f'({n("final_nat_credit", nat_s.get("credit_sum", float("nan")), "g", src_s, "correct free-choice trials (a tie counts one half)")} of '
          f'{n("final_nat_n", nat_s.get("n", 0), "d", src_s, "free-choice trials")}); k = 3 attempts of one person and '
          f'hand (mean P(right), harness k-curve): '
          f'{n.pct("final_kthree", k3["accuracy"], src_s, "final model as shipped: k = 3")} '
          f'{n.ci("final_kthree", k3["ci"], src_s, "final model as shipped: k = 3")}' + _shown_k3(n) + '.\n')
    if ns:
        nn, o = ns['nested'], ns['optimism']
        w(f'- **Selection-aware estimate of the whole cross-lane selection** (nested; {n_c} candidates): accuracy '
          f'{n.pct("nested_accuracy", nn["accuracy"], src_n, "nested selection: accuracy")} '
          f'{n.ci("nested_accuracy", nn["accuracy_ci"], src_n, "nested selection: accuracy")}, AUC '
          f'{n("nested_auc", nn["auc"], ".3f", src_n, "nested selection: AUC")} '
          f'{n.ci("nested_auc", nn["auc_ci"], src_n, "nested selection: AUC", ".3f")}, log loss '
          f'{n("nested_log_loss", nn["log_loss"], ".3f", src_n, "nested selection: log loss")} '
          f'{n.ci("nested_log_loss", nn["log_loss_ci"], src_n, "nested selection: log loss", ".3f")}. The best candidate '
          f'by outer log loss ({lab.get(ns["naive_key"], ns["naive_key"])}, exploratory) reaches '
          f'{n.pct("naive_accuracy", ns["naive"]["accuracy"], src_n, "best on the outer folds: accuracy")}: optimism '
          f'{n.pts("optimism_accuracy", o["accuracy"]["diff"], src_n, "optimism of the naive pick: accuracy")} points '
          f'{n.pts_ci("optimism_accuracy", o["accuracy"]["ci"], src_n, "optimism: accuracy")}, log loss '
          f'{n("optimism_log_loss", o["log_loss"]["diff"], "+.3f", src_n, "optimism of the naive pick: log loss")} '
          f'{n.ci("optimism_log_loss", o["log_loss"]["ci"], src_n, "optimism: log loss", "+.3f")}.\n')
    if cal:
        ov = cal['methods'][chosen]['overall']
        w(f'- Calibration (shipped remedy: **{chosen}**): ECE {n("final_cal_ece", ov["ece"], ".3f", src_c, "final model as shipped: ECE")} '
          f'(perfect-calibration 95 % band up to {n("final_cal_ece_null_hi", ov["ece_null_hi"], ".3f", src_c, "final model as shipped: upper end of the ECE null band")}), '
          f'slope {n("final_cal_slope", ov["slope"], ".2f", src_c, "final model as shipped: calibration slope")} '
          f'{n.ci("final_cal_slope", ov["slope_ci"], src_c, "final model as shipped: slope", ".2f")}, intercept '
          f'{n("final_cal_intercept", ov["intercept"], "+.2f", src_c, "final model as shipped: intercept")} '
          f'{n.ci("final_cal_intercept", ov["intercept_ci"], src_c, "final model as shipped: intercept", "+.2f")}: '
          f'{"miscalibrated" if ov["miscalibrated"] else "consistent with calibration"}.\n')
    from stage2.lanes.final_summary_body import body
    body(n, w, lab, fin, dec, master, cal, ns)
    _figure_counts(n, master)
    L.write_numbers(n.entries)
    L.summary_path.write_text('\n'.join(S) + '\n', encoding='utf-8')


def _shown_k3(n: Num) -> str:
    """The clause on the displayed aggregate at k = 3 (sigmoid(sum of logits / tau_3)), from the aggregation file."""
    if not _has('final_aggregation'):
        return ''
    v = ((_read('final_aggregation').get('rules') or {}).get('3') or {}).get('sum_tau')
    if not isinstance(v, dict):
        return ''
    src = _src('final_aggregation')
    return (f'; the displayed aggregate sigmoid(sum of logits / tau_3) is right in '
            f'{n.pct("final_kthree_shown", v["accuracy"], src, "displayed aggregate at k = 3: accuracy per person and hand")} '
            f'per person and hand, confidence minus accuracy '
            f'{n("final_kthree_over", v["over_confidence"], "+.3f", src, "displayed aggregate at k = 3: over-confidence")} '
            f'{n.ci("final_kthree_over", v["over_ci"], src, "displayed aggregate at k = 3: over-confidence", "+.3f")} '
            f'({"calibrated: the CI contains 0" if v["calibrated"] else "miscalibrated: the CI excludes 0"})')


def finalist_entry() -> dict[str, Any]:
    """The finalists entry of the final model (from the saved derived files): rebuildable through the convention
    ``getattr(import_module(module), factory)(**params)`` on ``getattr(module, build_x)(d)``."""
    from stage2.lanes import final_candidates as FC
    from stage2.lanes import final_experiments as FE
    dec = _read('final_decision')
    fin = dec['final_model']
    cands = FC.candidates()
    c = cands[fin]
    cal = _read('final_calibration') if _has('final_calibration') else {}
    chosen = cal.get('chosen', 'none')
    name = f'final_cal_{fin}_{chosen}'
    master = {r['key']: r for r in _read('final_master')['rows']}[fin]
    return {
        'name': name, 'results_json': f'results/{name}.json', 'module': 'stage2.lanes.final_experiments',
        'build_x': 'build_x_final', 'factory': 'finalist_factory', 'params': {'candidate': fin, 'method': chosen},
        'n_configs_tried': int(c.n_configs_tried),
        'notes': (f'{c.label}: the final model of the cross-lane synthesis (decision table tables/final/final_decision.csv;'
                  f' the decision rule recommends {dec["recommended"]}); shipped calibration remedy {chosen} (on top of '
                  f'its own in-fold calibration); LOSO accuracy {100 * master["accuracy"]:.1f} %, log loss '
                  f'{master["log_loss"]:.3f}; selected among {len(cands)} candidates after {int(c.n_configs_tried)} '
                  f'configurations in its lane (exploratory; the nested estimate is final_nested_select); exported to '
                  f'reports/stage2/export/final_model.json (numpy reference: stage2/lanes/final_infer.py).'),
        'candidate': fin, 'candidate_spec': FC.describe(c), 'source_result': FE.base_result_name(c),
        'export': 'reports/stage2/export/final_model.json'}


def finalists() -> None:
    """results/finalists_final.json = [the final model], rebuildable from this lane's modules."""
    L.write_finalists([finalist_entry()])


